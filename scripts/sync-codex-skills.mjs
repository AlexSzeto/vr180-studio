import { cp, mkdir, readdir, realpath, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.resolve(scriptDir, '..')

const syncSets = [
  {
    label: 'skills',
    source: path.join(projectRoot, '.claude', 'skills'),
    targets: [
      path.join(projectRoot, '.codex', 'skills'),
      path.join(projectRoot, '.agents', 'skills'),
    ],
    includeEntry: (entry) =>
      entry.isDirectory() && entry.name !== 'sync-skills',
  },
  {
    label: 'rules',
    source: path.join(projectRoot, '.claude', 'rules'),
    targets: [
      path.join(projectRoot, '.codex', 'rules'),
      path.join(projectRoot, '.agents', 'rules'),
    ],
    includeEntry: () => true,
  },
]

async function pathExists(directory) {
  try {
    await realpath(directory)
    return true
  } catch (error) {
    if (error.code === 'ENOENT') {
      return false
    }

    throw error
  }
}

function isInsideProject(resolvedTarget, resolvedProject) {
  const relative = path.relative(resolvedProject, resolvedTarget)
  return (
    relative === '' ||
    (!relative.startsWith('..') && !path.isAbsolute(relative))
  )
}

async function syncTree({ label, source, target, includeEntry }) {
  await mkdir(path.dirname(target), { recursive: true })

  if (await pathExists(target)) {
    const resolvedProject = await realpath(projectRoot)
    const resolvedTarget = await realpath(target)

    if (!isInsideProject(resolvedTarget, resolvedProject)) {
      throw new Error(
        `Refusing to remove target outside project root: ${resolvedTarget}`,
      )
    }

    await rm(target, { recursive: true, force: true })
  }

  await mkdir(target, { recursive: true })

  const entries = await readdir(source, { withFileTypes: true })
  for (const entry of entries) {
    if (!includeEntry(entry)) {
      continue
    }

    await cp(path.join(source, entry.name), path.join(target, entry.name), {
      recursive: true,
    })
  }

  console.log(`Synced ${label} from ${source} to ${target}`)
}

for (const syncSet of syncSets) {
  if (!(await pathExists(syncSet.source))) {
    throw new Error(
      `Claude ${syncSet.label} directory not found: ${syncSet.source}`,
    )
  }

  for (const target of syncSet.targets) {
    await syncTree({ ...syncSet, target })
  }
}

// Codex reads a root AGENTS.md on every run but never auto-loads .codex/rules —
// that folder holds its command-approval policy, not instructions — so without
// this file the rules reached Codex only when a skill happened to point at them.
// The rule list is regenerated from .claude/rules on each sync so it never drifts.
async function writeAgentsMd() {
  const rulesDir = path.join(projectRoot, '.claude', 'rules')
  const ruleFiles = (await readdir(rulesDir, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => entry.name)
    .sort()

  const content = [
    '# AGENTS.md',
    '',
    '<!-- Generated by scripts/sync-codex-skills.mjs (npm run sync:codex-skills). Do not edit by hand. -->',
    '',
    "This project's conventions live in `.claude/rules/`, the canonical source shared with Claude Code.",
    '**Before writing or changing any code, read every file listed below in full** and follow it.',
    'They hold rules that are easy to miss without reading them: the AnyTale Play glass-kit exception, theme tokens over hardcoded values, component reuse, testing, card and git workflow.',
    '',
    ...ruleFiles.map((name) => `- \`.claude/rules/${name}\``),
    '',
    'Read them even when a skill does not point you there, and read them again after any context reset.',
    'Where a rule mentions `AskUserQuestion`, present the decision as a numbered list instead, recommended option first and labelled `(Recommended)`.',
    '',
    'Project workflow skills are mirrored into `.codex/skills/` from `.claude/skills/`.',
    '',
  ].join('\n')

  await writeFile(path.join(projectRoot, 'AGENTS.md'), content)
  console.log(`Wrote AGENTS.md listing ${ruleFiles.length} rule files`)
}

await writeAgentsMd()
